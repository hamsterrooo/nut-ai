import type { GramPathway, Item, IngredientRow } from '@nutai/core-schema'

/**
 * Confidence and calibration.
 *
 * SPEC-accuracy-engine.md §7.
 *
 * WHY THE MODEL'S OWN CONFIDENCE NUMBER IS NOT THE ANSWER.
 *
 * Verbalized LLM confidence is measurably miscalibrated. Xiong et al.,
 * "Can LLMs Express Their Uncertainty?" (arXiv:2306.13063), finds models "tend to
 * be overconfident, potentially imitating human patterns of expressing
 * confidence", and that black-box confidence elicitation trails white-box
 * internal-probability methods by an AUROC gap of 0.522 to 0.605.
 *
 * Under bring-your-own-key we never see token probabilities — we get back
 * whatever JSON the API returns — so we are STRUCTURALLY CONFINED to the worse
 * side of that gap. Small-classifier softmax has the mirror-image problem:
 * overconfident without temperature scaling.
 *
 * So the model's self-report is a MODIFIER, never the signal. The primary signal
 * is measured per-pathway and per-category error from our own eval harness.
 *
 * And the bar to clear is not "perfectly calibrated Bayesian intervals". The
 * incumbent shows no confidence score, error range, or uncertainty indicator of
 * any kind, while its FAQ concedes "CalAI is about 80% accurate" and its blog
 * boilerplate claims 90% — two different self-reported numbers from one company,
 * neither per-scan, neither sourced. The bar is showing ANY honest measured
 * signal at all.
 */

export type FoodCategory =
  | 'whole_food'
  | 'packaged_labeled'
  | 'simple_cooked'
  | 'mixed_composite'
  | 'hidden_fat_likely'
  | 'liquid'

export type InferencePath = 'cloud' | 'local'

export type BandTier = 'none' | 'tight' | 'moderate' | 'wide' | 'very_wide'

export interface Band {
  halfPct: number
  tier: BandTier
  /** Plain-language reasons, shown when the user taps the confidence chip. */
  reasons: string[]
}

/** Never display a band wider than this — past it, say it in words instead. */
export const MAX_DISPLAYED_HALF_PCT = 0.6

/**
 * Measured baselines, shipped as DATA and regenerated by the eval harness.
 *
 * Before the harness has ever run this ships seeded from the §4.9 literature
 * table, every value traceable to a cited MAPE/PMAE figure. The file records
 * which values are measured and which are still seeded, and the "How accurate is
 * this?" page shows that distinction — because claiming a measured number we have
 * not measured would be the exact dishonesty this product exists to avoid.
 */
export interface MeasuredBaselines {
  pathwayHalfPct: Record<GramPathway, number>
  categoryHalfPct: Record<FoodCategory, number>
  localPathMultiplier: number
  provenance: Record<string, 'seeded' | 'measured'>
  generatedAt: string | null
}

